"""Experiment 2 analysis: cue-sweep calibration (k_L), instructed contrast, decision rule per model.
usage: python analyze2.py  -> prints and writes RESULTS2_tables.md, results2.json"""
import glob, json, os, sys
from collections import defaultdict
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'exp1'))
import analyze as A1  # load, pooled, decision, wilson

RNG = np.random.default_rng(7)
EXPECTED = {os.path.basename(f)[:-6]: sum(1 for _ in open(f, encoding='utf-8')) for f in glob.glob(os.path.join(HERE, '..', 'exp1', 'stim', '*.jsonl'))}


def sweep(path):
    """{(variant, k, t): {class: [correct, total, sum_pgold]}}"""
    agg = defaultdict(lambda: defaultdict(lambda: [0, 0, 0.0]))
    trials = defaultdict(list)
    for l in open(path, encoding='utf-8'):
        r = json.loads(l)
        var = 'instr' if r['file'].startswith('ki_') else ('sorted' if r['file'].startswith('kso_') else 'raw')
        key = (var, r['k'], r['t'])
        per = defaultdict(lambda: [0, 0, 0.0])
        for q in r['queries']:
            for d in (agg[key][q['class']], per[q['class']]):
                d[0] += q['correct']; d[1] += 1; d[2] += q['p_gold']
        trials[key].append(dict(per))
    return agg, trials


def boot_diff(tr_a, tr_b, cls, nb=2000):
    """bootstrap CI of pooled acc(a) - acc(b) on class cls (independent trial sets)"""
    def pool(tr, idx):
        c = sum(tr[i][cls][0] for i in idx if cls in tr[i]); n = sum(tr[i][cls][1] for i in idx if cls in tr[i])
        return c / n if n else np.nan
    d = []
    for _ in range(nb):
        ia = RNG.integers(0, len(tr_a), len(tr_a)); ib = RNG.integers(0, len(tr_b), len(tr_b))
        d.append(pool(tr_a, ia) - pool(tr_b, ib))
    return float(np.nanpercentile(d, 2.5)), float(np.nanpercentile(d, 97.5))


def main():
    md = ['# Experiment 2: result tables (auto-generated by analyze2.py)']
    summary = {}
    for path in sorted(glob.glob(os.path.join(HERE, 'res', '*_cal.jsonl'))):
        model = os.path.basename(path)[:-len('_cal.jsonl')]
        agg, trials = sweep(path)
        md.append(f'\n## {model}: cue sweep (n=6)\n')
        md.append('| variant | k | t | L | O | G | U |')
        md.append('|---|---|---|---|---|---|---|')
        for key in sorted(agg):
            row = [key[0], str(key[1]), str(key[2])]
            for cl in ['L', 'O', 'G', 'U']:
                c, n, _ = agg[key][cl]
                row.append('—' if n == 0 else f'{c / n:.3f} (n={n})')
            md.append('| ' + ' | '.join(row) + ' |')
        # k_L: pooled over t, raw variant
        kL = None; curve = {}
        for k in sorted({key[1] for key in agg if key[0] == 'raw'}):
            c = sum(agg[('raw', k, t)]['L'][0] for t in (0, 4) if ('raw', k, t) in agg)
            n = sum(agg[('raw', k, t)]['L'][1] for t in (0, 4) if ('raw', k, t) in agg)
            curve[k] = c / n if n >= 30 else float('nan')  # fewer than 30 L cells: not estimable
            if kL is None and n >= 30 and c / n >= 0.5:
                kL = k
        md.append(f'\nL-accuracy by k (pooled t): ' + ', '.join(f'k={k}: {v:.3f}' for k, v in curve.items()) + f'  →  **k_L = {kL}**')
        # t=4 minus t=0 on G and O at each k (raw)
        lines = []
        for k in sorted(curve):
            for cl in ['G', 'O', 'L']:
                a, b = trials.get(('raw', k, 4)), trials.get(('raw', k, 0))
                if not a or not b:
                    continue
                ca = sum(x[cl][0] for x in a if cl in x); na = sum(x[cl][1] for x in a if cl in x)
                cb = sum(x[cl][0] for x in b if cl in x); nb_ = sum(x[cl][1] for x in b if cl in x)
                if na < 30 or nb_ < 30:
                    continue
                lo, hi = boot_diff(a, b, cl)
                lines.append(f'k={k} {cl}: {ca / na - cb / nb_:+.3f} [{lo:+.3f},{hi:+.3f}]')
        md.append('t=4 minus t=0 (raw): ' + '; '.join(lines))
        # instructed minus raw
        il = []
        for key in sorted(agg):
            if key[0] != 'instr':
                continue
            rk = ('raw', key[1], key[2])
            for cl in ['L', 'O', 'G']:
                ci, ni, _ = agg[key][cl]; cr, nr, _ = agg[rk][cl]
                if ni >= 30 and nr >= 30:
                    il.append(f'k={key[1]} t={key[2]} {cl}: {ci / ni - cr / nr:+.3f}')
        md.append('instructed minus raw: ' + '; '.join(il))
        summary[model] = {'kL': kL, 'L_curve': curve}
    for path in sorted(glob.glob(os.path.join(HERE, 'res', '*_main.jsonl'))):
        model = os.path.basename(path)[:-len('_main.jsonl')]
        cells = A1.load(path)
        bad = {c: len(cells.get(c, {'trials': []})['trials']) for c in EXPECTED if len(cells.get(c, {'trials': []})['trials']) != EXPECTED[c]}
        if bad:  # audit fix: never report numbers from incomplete runs
            ntr = sum(len(v['trials']) for v in cells.values())
            md.append(f'\n## {model}: main cells PENDING ({ntr}/1800 trials; incomplete cells: {len(bad)})')
            continue
        md.append(f'\n## {model}: main cells\n')
        for prefix, n in [('n6', 6), ('n8', 8)]:
            s = A1.decision(cells, n, prefix, 0)
            if s is None:
                continue
            r, rc = s['raw'], s['raw_ci']
            G = s['G']
            md.append(f'- {prefix}: class **{s["class"]}**, acc_L={s["accL"]:.3f}; G t0={G[prefix + "_base_t0"]:.3f} t1={G[prefix + "_base_t1"]:.3f} '
                      f't4={G[prefix + "_base_t4"]:.3f} scr4={G[prefix + "_scramble_t4"]:.3f} held4={G[prefix + "_heldout_t4"]:.3f}; '
                      + '; '.join(f'{k}={r[k]:+.3f} [{rc[k][0]:+.3f},{rc[k][1]:+.3f}]' for k in r))
            summary.setdefault(model, {})[f'{prefix}_class'] = s['class']
            summary[model][f'{prefix}_raw'] = r
            summary[model][f'{prefix}_raw_ci'] = rc
            summary[model][f'{prefix}_G'] = G
            summary[model][f'{prefix}_accL'] = s['accL']
        if 'n6_leak_t1' in cells:
            a, _ = A1.pooled(cells['n6_leak_t1']['trials'], 'G')
            md.append(f'- leak (n6, t=1) G acc = {a:.3f}')
            summary[model]['leak_G'] = a
    txt = '\n'.join(md)
    print(txt)
    open(os.path.join(HERE, 'RESULTS2_tables.md'), 'w', encoding='utf-8').write(txt + '\n')
    json.dump(summary, open(os.path.join(HERE, 'results2.json'), 'w'), indent=1, default=float)


if __name__ == '__main__':
    main()

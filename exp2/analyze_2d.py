"""Addendum 2d operating point (k=16), applied post-audit (2026-10-09) to the two models that trigger it under the literal 2a rule.
Unchanged Experiment-1 decision rule, with acc_L from the k=16 base t0 cell. -> RESULTS_2d.md"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'exp1'))
import analyze as A1
md = ['# Addendum 2d: k=16 operating point (auto-generated by analyze_2d.py)', '',
      'Triggered under the literal 2a rule (no ≥30-query guard): k=6 L accuracy 2/4 = 0.50 for both models, and both are R at k=10. '
      'Run on 2026-10-09 after the final audit; stimuli from make_stim_k16.py (new seeds). Chance 0.167; R threshold acc_L < 0.417.', '',
      '| model | trials | class (acc / p_gold) | acc_L (k16, t0) [95% CI] | G t0 | G t4 | G scr4 | G held4 | t4 − scr [95% CI] |', '|---|---|---|---|---|---|---|---|---|']
for name, lab in [('q06b', 'Qwen3-0.6B-Base'), ('q17b', 'Qwen3-1.7B-Base')]:
    p = os.path.join(HERE, 'res', f'{name}_k16.jsonl')
    if not os.path.exists(p):
        md.append(f'| {lab} | not run | | | | | | | |'); continue
    cells = A1.load(p); nt = sum(len(c['trials']) for c in cells.values())
    a = A1.decision(cells, 6, 'n6', 0); b = A1.decision(cells, 6, 'n6', 2)
    if a is None:
        md.append(f'| {lab} | {nt} (incomplete) | | | | | | | |'); continue
    G = a['G']; r, rc = a['raw']['dG_t4_scr'], a['raw_ci']['dG_t4_scr']
    md.append(f"| {lab} | {nt} | **{a['class']}** / {b['class']} | {a['accL']:.3f} [{a['ci']['accL'][0]:.3f}, {a['ci']['accL'][1]:.3f}] | "
              f"{G['n6_base_t0']:.3f} | {G['n6_base_t4']:.3f} | {G['n6_scramble_t4']:.3f} | {G['n6_heldout_t4']:.3f} | {r:+.3f} [{rc[0]:+.3f}, {rc[1]:+.3f}] |")
txt = '\n'.join(md); print(txt)
open(os.path.join(HERE, 'RESULTS_2d.md'), 'w', encoding='utf-8').write(txt + '\n')

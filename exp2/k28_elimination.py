"""How informative is the densest cue? For ks_n6_k28 (100 trials, all 8 missing cells queried): share of Latin-forced
cells, share of L cells left with a single candidate by one-pass row/column elimination, and the expected accuracy of
that elimination (uniform among remaining candidates). -> k28_elimination.md"""
import json, os, re
from collections import defaultdict
HERE = os.path.dirname(os.path.abspath(__file__))
FACT = re.compile(r'^(\S+) \* (\S+) = (\S+)$')
n_q = n_L = single_L = 0; acc = []
for tr in map(json.loads, open(os.path.join(HERE, 'stim', 'ks_n6_k28.jsonl'), encoding='utf-8')):
    cue = [FACT.match(x).groups() for x in tr['context'].split('Table ')[-1].split('\n')[1:] if FACT.match(x)]
    row, col = defaultdict(set), defaultdict(set)
    for a, b, c in cue:
        row[a].add(c); col[b].add(c)
    for q in tr['queries']:
        wa, wb = re.findall(r'\S+', q['prompt_suffix'].replace('*', ' ').replace('=', ' '))[:2]
        feas = [w for w in tr['target_words'] if w not in row[wa] and w not in col[wb]]
        n_q += 1; acc.append((q['gold'] in feas) / len(feas))
        if q['class'] == 'L':
            n_L += 1; single_L += len(feas) == 1
txt = (f'# ks_n6_k28: informativeness of the densest cue (auto-generated by k28_elimination.py)\n\n'
       f'- queried cells: {n_q}; Latin-forced: {n_L} ({n_L / n_q:.3f})\n'
       f'- L cells with a single candidate after one-pass row/column elimination: {single_L} of {n_L} ({single_L / n_L:.3f})\n'
       f'- expected accuracy of one-pass row/column elimination over all queried cells: {sum(acc) / len(acc):.3f}\n')
print(txt); open(os.path.join(HERE, 'k28_elimination.md'), 'w', encoding='utf-8').write(txt)

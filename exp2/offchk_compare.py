"""Compare scoring paths (post-audit, 2026-10-09): standard vs CPU-offload (embeddings + fp32 head), batch 1, same trials;
and Qwen3-1.7B-Base primary-contrast cells re-scored with one code version (B=1) vs the original mixed-version file.
-> offchk_result.md"""
import json, os, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'exp1'))
md = ['# Scoring-path checks (auto-generated by offchk_compare.py)', '']


def load(p):
    return {(r['file'], r['trial']): r for r in map(json.loads, open(os.path.join(HERE, p), encoding='utf-8'))} if os.path.exists(os.path.join(HERE, p)) else {}


for lab, a, b in [('Qwen3-1.7B-Base bf16: standard vs offload (CPU embeddings, fp32 CPU head)', 'res/_offchk_q17b_std.jsonl', 'res/_offchk_q17b_off.jsonl'),
                  ('Qwen3-4B-Base nf4: standard vs nf4 + offload (the 8B configuration)', 'res/_offchk_q4b_std.jsonl', 'res/_offchk_q4b_off.jsonl')]:
    A, B = load(a), load(b)
    keys = sorted(set(A) & set(B))
    if not keys:
        md.append(f'- {lab}: not available'); continue
    agree = dp = n = 0; mx = 0.0; ca = cb = 0
    for k in keys:
        for qa, qb in zip(A[k]['queries'], B[k]['queries']):
            assert qa['cell'] == qb['cell']
            agree += qa['pred'] == qb['pred']; d = abs(qa['p_gold'] - qb['p_gold']); mx = max(mx, d); dp += d; n += 1
            ca += qa['correct']; cb += qb['correct']
    md.append(f'- {lab}: {len(keys)} trials, {n} queries; argmax agreement {agree}/{n} = {agree / n:.3f}; '
              f'mean |Δp_gold| {dp / n:.4f}, max {mx:.4f}; accuracy {ca / n:.4f} vs {cb / n:.4f}')
R = load('res/_rescore_q17b_b1.jsonl'); O = load('res/q17b_main.jsonl')
if R:
    md += ['', '## Qwen3-1.7B-Base n=6 cells re-scored with the final code, B=1 (sequential), vs the original file', '']
    for f in ['n6_base_t0.jsonl', 'n6_base_t4.jsonl', 'n6_scramble_t4.jsonl', 'n6_heldout_t4.jsonl']:
        ks = [k for k in R if k[0] == f]
        if not ks:
            continue
        g = lambda D: [q for k in ks for q in D[k]['queries'] if q['class'] == 'G']
        gr, go = g(R), g(O)
        agree = np.mean([x['pred'] == y['pred'] for k in ks for x, y in zip(R[k]['queries'], O[k]['queries'])])
        md.append(f'- {f}: {len(ks)} trials; G acc re-scored {np.mean([q["correct"] for q in gr]):.3f} vs original {np.mean([q["correct"] for q in go]):.3f}; '
                  f'all-query argmax agreement {agree:.3f}')
    # primary contrast on the re-scored cells, same bootstrap as exp1/analyze (trial resampling)
    def gacc(D, f, idx):
        c = n = 0
        for t in idx:
            for q in D[(f, t)]['queries']:
                if q['class'] == 'G':
                    c += q['correct']; n += 1
        return c / n
    rng = np.random.default_rng(20261009)
    t4 = sorted(t for (f, t) in R if f == 'n6_base_t4.jsonl'); sc = sorted(t for (f, t) in R if f == 'n6_scramble_t4.jsonl')
    if len(t4) == 100 and len(sc) == 100:
        for lab, D in [('re-scored (single version, B=1)', R), ('original file', O)]:
            d = gacc(D, 'n6_base_t4.jsonl', t4) - gacc(D, 'n6_scramble_t4.jsonl', sc)
            bs = [gacc(D, 'n6_base_t4.jsonl', rng.choice(t4, 100)) - gacc(D, 'n6_scramble_t4.jsonl', rng.choice(sc, 100)) for _ in range(2000)]
            md.append(f'- t4 − scramble (G, n=6), {lab}: {d:+.3f} [{np.percentile(bs, 2.5):+.3f}, {np.percentile(bs, 97.5):+.3f}]')
txt = '\n'.join(md); print(txt)
open(os.path.join(HERE, 'offchk_result.md'), 'w', encoding='utf-8').write(txt + '\n')

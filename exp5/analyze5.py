"""Experiment 5 analysis (PREREGISTRATION.md): H1 base_t1 vs leak_t1 CR projection; H2 class trend L<O<G; exploratory.
usage: python analyze5.py -> prints, writes RESULTS_tables.md and results5.json"""
import json, os, zlib
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
MODELS = [('q06b', 'Qwen3-0.6B-Base', 'exp2/res/q06b_main.jsonl'), ('q17b', 'Qwen3-1.7B-Base', 'exp2/res/q17b_main.jsonl'),
          ('q17', 'Qwen3-1.7B', 'exp1/res/qwen3-1.7b.jsonl'), ('q4b', 'Qwen3-4B-Base (nf4)', 'exp2/res/q4b_main.jsonl'),
          ('q8b', 'Qwen3-8B-Base (nf4)', 'exp2/res/q8b_main.jsonl')]
RANK = {'L': 0, 'O': 1, 'G': 2}
NB = 2000


def auc(pos, neg):
    pos, neg = np.asarray(pos), np.asarray(neg)
    x = np.concatenate([pos, neg]); order = np.argsort(x, kind='mergesort'); r = np.empty(len(x)); xs = x[order]; i = 0
    while i < len(xs):
        j = i
        while j + 1 < len(xs) and xs[j + 1] == xs[i]:
            j += 1
        r[order[i:j + 1]] = (i + j) / 2 + 1; i = j + 1
    return (r[:len(pos)].sum() - len(pos) * (len(pos) + 1) / 2) / (len(pos) * len(neg))


def spearman(x, y):
    rx = np.argsort(np.argsort(x, kind='mergesort'), kind='mergesort').astype(float)
    # average ranks for ties in x (class ranks are heavily tied)
    for v in np.unique(x):
        m = x == v; rx[m] = rx[m].mean()
    ry = np.argsort(np.argsort(y, kind='mergesort'), kind='mergesort').astype(float)
    return float(np.corrcoef(rx, ry)[0, 1])


def load(name):
    p = os.path.join(HERE, 'res', f'{name}.jsonl')
    if not os.path.exists(p):
        return None, None
    meta = json.load(open(os.path.join(HERE, 'res', f'{name}_meta.json'))) if os.path.exists(os.path.join(HERE, 'res', f'{name}_meta.json')) else None
    return [json.loads(l) for l in open(p, encoding='utf-8')], meta


def correctness(path):
    p = os.path.join(ROOT, path)
    if not os.path.exists(p):
        return {}
    out = {}
    for l in open(p, encoding='utf-8'):
        r = json.loads(l)
        for q in r['queries']:
            out[(r['file'].replace('.jsonl', ''), r['trial'], tuple(q['cell']))] = q['correct']
    return out


def main():
    md = ['# Experiment 5: CR-axis projections on the fingerprint trials (auto-generated by analyze5.py)', '']
    summ = {}
    for name, lab, respath in MODELS:
        rows, meta = load(name)
        if not rows or not meta:
            md.append(f'## {lab}: PENDING'); continue
        L = str(meta['best_layer'])
        corr = correctness(respath)
        by = {}
        for r in rows:
            by.setdefault(r['file'], []).append(r)
        def tmeans(f, fmt='det', layer=L):
            return np.array([np.mean([q[f'proj_{fmt}'][layer] for q in r['queries']]) for r in by.get(f, [])])
        res = {'calib_auc': meta['calib_auc'], 'best_layer': meta['best_layer'], 'verify': meta.get('verify_max_rel_diff')}
        md.append(f"## {lab}\n\nCalibration AUC by layer {meta['calib_auc']} → layer **{L}**" +
                  (f"; equivalence vs CRDetector: max rel. diff {meta['verify_max_rel_diff']:.2e}" if meta.get('verify_max_rel_diff') is not None else ''))
        # H1 (primary: det format, best layer) and the same for raw format + all layers (exploratory)
        for fmt in ('det', 'raw'):
            for layer in [L] + [l for l in meta['calib_auc'] if l != L]:
                b, k = tmeans('n6_base_t1', fmt, layer), tmeans('n6_leak_t1', fmt, layer)
                d = b.mean() - k.mean()
                rng = np.random.default_rng([5, zlib.crc32(name.encode()), int(layer), int(fmt == 'raw')])  # per-test seed
                bs = [rng.choice(b, len(b)).mean() - rng.choice(k, len(k)).mean() for _ in range(NB)]
                lo, hi = np.percentile(bs, [2.5, 97.5]); sd = np.sqrt((b.var(ddof=1) + k.var(ddof=1)) / 2)
                qb = [q[f'proj_{fmt}'][layer] for r in by['n6_base_t1'] for q in r['queries']]
                qk = [q[f'proj_{fmt}'][layer] for r in by['n6_leak_t1'] for q in r['queries']]
                tag = 'H1 (primary)' if (fmt == 'det' and layer == L) else 'exploratory'
                md.append(f'- {tag}, {fmt} format, layer {layer}: base_t1 − leak_t1 = {d:+.4f} [{lo:+.4f}, {hi:+.4f}]; d = {d / sd:+.2f}; query AUC (base>leak) = {auc(qb, qk):.3f}')
                if fmt == 'det' and layer == L:
                    res['H1'] = {'diff': d, 'ci': [lo, hi], 'd': d / sd, 'auc': auc(qb, qk), 'supported': bool(lo > 0)}
        # H2: class trend within base_t1 (det, best layer)
        xs = np.array([RANK[q['class']] for r in by['n6_base_t1'] for q in r['queries'] if q['class'] in RANK])
        ys = np.array([q['proj_det'][L] for r in by['n6_base_t1'] for q in r['queries'] if q['class'] in RANK])
        rho = spearman(xs, ys)
        trials = by['n6_base_t1']; bsr = []
        rng = np.random.default_rng([6, zlib.crc32(name.encode())])  # per-test seed
        for _ in range(NB):
            pick = [trials[i] for i in rng.integers(0, len(trials), len(trials))]
            x = np.array([RANK[q['class']] for r in pick for q in r['queries'] if q['class'] in RANK])
            y = np.array([q['proj_det'][L] for r in pick for q in r['queries'] if q['class'] in RANK])
            bsr.append(spearman(x, y))
        lo, hi = np.percentile(bsr, [2.5, 97.5])
        means = {c: float(np.mean([q['proj_det'][L] for r in trials for q in r['queries'] if q['class'] == c])) for c in RANK}
        md.append(f'- H2: Spearman ρ(class rank L<O<G, projection) = {rho:+.3f} [{lo:+.3f}, {hi:+.3f}]; class means ' +
                  ', '.join(f'{c} {v:+.3f}' for c, v in means.items()))
        res['H2'] = {'rho': rho, 'ci': [lo, hi], 'class_means': means}
        # exploratory: history effect; projection vs correctness
        b0, b4 = tmeans('n6_base_t0'), tmeans('n6_base_t4')
        md.append(f'- exploratory: base_t4 − base_t0 = {b4.mean() - b0.mean():+.4f}')
        for f in ('n6_base_t1', 'n6_leak_t1'):
            pc = [q['proj_det'][L] for r in by[f] for q in r['queries'] if corr.get((f, r['trial'], tuple(q['cell']))) == 1]
            pw = [q['proj_det'][L] for r in by[f] for q in r['queries'] if corr.get((f, r['trial'], tuple(q['cell']))) == 0]
            if len(pc) >= 20 and len(pw) >= 20:
                md.append(f'- exploratory: {f}: AUC(projection; wrong vs correct) = {auc(pw, pc):.3f} (n correct {len(pc)}, wrong {len(pw)})')
        summ[name] = res
        md.append('')
    n_sup = sum(1 for v in summ.values() if v.get('H1', {}).get('supported'))
    md.insert(2, f'**H1 decision rule (≥3 of 5 models with CI excluding 0 in the predicted direction): {n_sup} of {len(summ)} completed models support H1.**\n')
    txt = '\n'.join(md); print(txt)
    open(os.path.join(HERE, 'RESULTS_tables.md'), 'w', encoding='utf-8').write(txt + '\n')
    json.dump(summ, open(os.path.join(HERE, 'results5.json'), 'w'), indent=1, default=float)


if __name__ == '__main__':
    main()

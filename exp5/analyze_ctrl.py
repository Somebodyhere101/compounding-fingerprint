"""Experiment 5b analysis (exploratory; CONTROL_vocab.md) -> RESULTS_ctrl.md, results_ctrl.json"""
import json, os, zlib
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
MODELS = [('q06b', 'Qwen3-0.6B-Base'), ('q17b', 'Qwen3-1.7B-Base'), ('q17', 'Qwen3-1.7B'), ('q4b', 'Qwen3-4B-Base (nf4)')]
CONDS = ['leak', 'leakRel', 'baseRel', 'base']
NB = 2000


def stats(M, rng):
    """M: {cond: array[trials]} -> point estimates and CIs; leak* and base* resampled independently."""
    def est(m):
        g = m['leak'].mean() - m['base'].mean()
        return {'base-leak': -g, 'baseRel-leak': m['baseRel'].mean() - m['leak'].mean(), 'leakRel-leak': m['leakRel'].mean() - m['leak'].mean(),
                'baseRel-base': m['baseRel'].mean() - m['base'].mean(), 'f_vocab': (m['baseRel'].mean() - m['base'].mean()) / g if g else np.nan}
    pt = est(M); n = len(M['leak']); bs = {k: [] for k in pt}
    for _ in range(NB):
        il, ib = rng.integers(0, n, n), rng.integers(0, n, n)
        e = est({'leak': M['leak'][il], 'leakRel': M['leakRel'][il], 'base': M['base'][ib], 'baseRel': M['baseRel'][ib]})
        for k in e:
            bs[k].append(e[k])
    return {k: (float(pt[k]), [float(x) for x in np.nanpercentile(bs[k], [2.5, 97.5])]) for k in pt}


def main():
    md = ['# Experiment 5b: vocabulary-overlap control (exploratory, not preregistered; auto-generated by analyze_ctrl.py)', '',
          'Trial-mean CR projections (published axis, detector layer). leak: retrievable history; leakRel: same words, answers inconsistent; '
          'baseRel: different group table in the target\'s words; base: different table in other words. '
          'f_vocab = (baseRel − base)/(leak − base) is the share of the base–leak gap reproduced by vocabulary alone; leak − baseRel is what remains for retrievability.', '']
    J = {}
    for name, lab in MODELS:
        p = os.path.join(HERE, 'res_ctrl', f'{name}.jsonl')
        if not os.path.exists(p):
            md.append(f'## {lab}: not run'); continue
        rows = [json.loads(l) for l in open(p, encoding='utf-8')]
        rows.sort(key=lambda r: r['trial'])
        L = str(rows[0]['best_layer']); layers = list(rows[0]['conds']['leak']['det'][0].keys())
        shared = {c: np.mean([r['conds'][c]['A_lines_shared_with_B'] for r in rows]) for c in CONDS}
        md.append(f'## {lab} ({len(rows)} trial pairs; detector layer {L})')
        md.append('Target (Table B) lines found verbatim in Table A: ' + ', '.join(f'{c} {v:.2f}' for c, v in shared.items()))
        md.append('')
        md.append('| format | layer | leak | leakRel | baseRel | base | base − leak [CI] (d) | leak − baseRel [CI] | leakRel − leak [CI] (paired d_z) | f_vocab [CI] |')
        md.append('|---|---|---|---|---|---|---|---|---|---|')
        J[name] = {}
        for fmt in ('det', 'raw'):
            for li in [L] + [x for x in layers if x != L]:
                M = {c: np.array([np.mean([q[li] for q in r['conds'][c][fmt]]) for r in rows]) for c in CONDS}
                S = stats(M, np.random.default_rng([zlib.crc32(name.encode()), int(li), int(fmt == 'raw')]))
                sd = np.sqrt((M['base'].var(ddof=1) + M['leak'].var(ddof=1)) / 2); d_bl = (M['base'].mean() - M['leak'].mean()) / sd
                dl = M['leakRel'] - M['leak']; dz = dl.mean() / dl.std(ddof=1)
                J[name][f'{fmt}_L{li}'] = {'means': {c: float(M[c].mean()) for c in CONDS}, 'd_base_leak': float(d_bl), 'sd_pooled': float(sd), 'dz_leakRel_leak': float(dz), **S}
                f = lambda k, s=1: f'{s * S[k][0]:+.2f} [{s * S[k][1][1 if s < 0 else 0]:+.2f}, {s * S[k][1][0 if s < 0 else 1]:+.2f}]'
                tag = ' **(primary)**' if (fmt == 'det' and li == L) else ''
                md.append(f'| {fmt} | {li}{tag} | ' + ' | '.join(f'{M[c].mean():+.2f}' for c in CONDS) +
                          f" | {f('base-leak')} ({d_bl:+.2f}) | {f('baseRel-leak', -1)} | {f('leakRel-leak')} ({dz:+.2f}) | "
                          f"{S['f_vocab'][0]:.2f} [{S['f_vocab'][1][0]:.2f}, {S['f_vocab'][1][1]:.2f}] |")
        md.append('')
    txt = '\n'.join(md); print(txt)
    open(os.path.join(HERE, 'RESULTS_ctrl.md'), 'w', encoding='utf-8').write(txt + '\n')
    json.dump(J, open(os.path.join(HERE, 'results_ctrl.json'), 'w'), indent=1)


if __name__ == '__main__':
    main()

"""Experiment 6 analysis (PREREGISTRATION.md) -> RESULTS_tables.md, results6.json.
Primary: decision-rule steps 1-3 (exp1/analyze.py formulas) on base t0; P1-P6. Secondary/exploratory as labelled."""
import json, os, re, sys, zlib
from collections import Counter, defaultdict
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, 'exp1'))
import analyze as A1  # load, pooled, wilson

NB = 2000
FACT = re.compile(r'^(\S+) \* (\S+) = (\S+)$')
SEEN8 = {'Z8', 'D4'}           # order-8 types in the model's training distribution (C8, D4)


def seed(*xs):
    return np.random.default_rng([zlib.crc32(str(x).encode()) for x in xs])


def cell_acc(cells, c, cls, field=0):
    return A1.pooled(cells[c]['trials'], cls, None, field)


def steps123(cells, n, prefix, field=0):
    """decision-rule steps 1-3 of exp1/analyze.decision on the base t0 cell only (+ trial bootstrap)."""
    c0 = f'{prefix}_base_t0'
    if c0 not in cells:
        return None
    ch = 1.0 / n; tr = cells[c0]['trials']

    def st(idx):
        aL = A1.pooled(tr, 'L', idx, field)[0]; G = A1.pooled(tr, 'G', idx, field)[0]
        g = (G - ch) / (aL - ch) if aL - ch > 1e-9 else float('nan')
        return aL, G, g
    aL, G, g = st(range(len(tr)))
    cls = 'R' if aL < ch + 0.25 else ('B-type' if g >= 0.85 else 'non-R, non-B (N/N_iso/A undetermined)')
    rng = np.random.default_rng(A1._seed(cells, prefix, field)); bs = []
    for _ in range(NB):
        bs.append(st(rng.integers(0, len(tr), len(tr))))
    bs = np.array(bs)
    ci = lambda j: [float(x) for x in np.nanpercentile(bs[:, j], [2.5, 97.5])]
    return {'class': cls, 'acc_L': aL, 'acc_L_ci': ci(0), 'n_L': A1.pooled(tr, 'L', None, field)[1], 'G_t0': G, 'G_t0_ci': ci(1),
            'g_G_t0': g, 'g_ci': ci(2), 'threshold_L': ch + 0.25}


def boot_diff(ta, tb, cls, rng, paired=False):
    def pool(tr, idx):
        c = sum(tr[i][cls][0] for i in idx if cls in tr[i]); n = sum(tr[i][cls][1] for i in idx if cls in tr[i])
        return c / n if n else np.nan
    est = pool(ta, range(len(ta))) - pool(tb, range(len(tb)))
    d = []
    for _ in range(NB):
        ia = rng.integers(0, len(ta), len(ta)); ib = ia if paired else rng.integers(0, len(tb), len(tb))
        d.append(pool(ta, ia) - pool(tb, ib))
    return float(est), [float(x) for x in np.nanpercentile(d, [2.5, 97.5])]


def heuristics(stim_path, t0_only=False):
    """per class: expected accuracy of learner C (count shortcut) and of one-pass row/column elimination (uniform ties)."""
    out = defaultdict(lambda: [[], []])
    for tr in map(json.loads, open(stim_path, encoding='utf-8')):
        if t0_only and tr['t'] != 0:
            continue
        target = [FACT.match(x).groups() for x in tr['context'].split('Table ')[-1].split('\n')[1:] if FACT.match(x)]
        cnt = Counter(c for _, _, c in target); words = tr['target_words']
        m = min(cnt.get(w, 0) for w in words); low = {w for w in words if cnt.get(w, 0) == m}
        row, col = defaultdict(set), defaultdict(set)
        for a, b, c in target:
            row[a].add(c); col[b].add(c)
        for q in tr['queries']:
            wa, wb = re.findall(r'\S+', q['prompt_suffix'].strip().rstrip('=').strip().replace('*', ' '))[:2]
            feas = [w for w in words if w not in row[wa] and w not in col[wb]] or words
            for key in (q['class'], 'all'):
                out[key][0].append((q['gold'] in low) / len(low)); out[key][1].append((q['gold'] in feas) / len(feas))
    return {k: (float(np.mean(v[0])), float(np.mean(v[1]))) for k, v in out.items()}


def main():
    md = ['# Experiment 6: In-Context Algebra checkpoint on the fingerprint (auto-generated by analyze6.py)', '']
    J = {}
    main_p = os.path.join(HERE, 'res', 'ica_best_main.jsonl')
    cells = A1.load(main_p)
    val = json.load(open(os.path.join(HERE, 'validate_algebra_gpt_best.json')))
    md.append(f"Adapter validation on the model's own distribution: held-out final fact at k=200 {val['k200']['acc']:.3f}, k=50 {val['k50']['acc']:.3f}, "
              f"k=20 {val['k20']['acc']:.3f} (see PREREGISTRATION.md).")
    vu = json.load(open(os.path.join(HERE, 'validate_unshuffled.json'))); vc = json.load(open(os.path.join(HERE, 'validate_ckpts.json')))
    md.append(f"Upstream protocol replica (fresh sequences, not the authors' cached 512-sequence set): {vu['unshuffled_k200_acc']:.3f}; released checkpoints on the same "
              f"{vc['n_sequences']} sequences: " + ', '.join(f"{k.replace('algebra_gpt_', '').replace('.pt', '')} {v['acc']:.3f}" for k, v in vc['checkpoints'].items()) +
              f". Independent forward pass vs the adapter: argmax agreement {vc['independent_forward']['argmax_agreement']:.3f} on "
              f"{vc['independent_forward']['answer_positions']} answer positions, max |logit diff| {vc['independent_forward']['max_abs_logit_diff']:.1e} (validate_ckpts.json).")
    md += ['', '## Accuracy by cell and forcing class (stimulus order, 4 symbol draws; chance = 1/n)', '',
           '| cell | trials | L | O | G | Ab | Cy | all |', '|---|---|---|---|---|---|---|---|']
    for c in sorted(cells, key=lambda s: (s[:2], s)):
        row = []
        for cls in ['L', 'O', 'G', 'Ab', 'Cy']:
            a, n = cell_acc(cells, c, cls)
            row.append(f'{a:.3f} (n={n})' if n else '—')
        tot = sum(v[0] for t in cells[c]['trials'] for v in t.values()) / sum(v[1] for t in cells[c]['trials'] for v in t.values())
        md.append(f"| {c} | {len(cells[c]['trials'])} | " + ' | '.join(row) + f' | {tot:.3f} |')
        J.setdefault('cells', {})[c] = {cls: cell_acc(cells, c, cls) for cls in ['L', 'O', 'G', 'Ab', 'Cy']}
    k16p = os.path.join(HERE, 'res', 'ica_best_k16.jsonl')
    if os.path.exists(k16p):
        c16t = A1.load(k16p)
        for c in sorted(c16t):
            row = [f'{cell_acc(c16t, c, cls)[0]:.3f} (n={cell_acc(c16t, c, cls)[1]})' if cell_acc(c16t, c, cls)[1] else '—' for cls in ['L', 'O', 'G', 'Ab', 'Cy']]
            tot = sum(v[0] for t in c16t[c]['trials'] for v in t.values()) / sum(v[1] for t in c16t[c]['trials'] for v in t.values())
            md.append(f"| {c} (k=16, 2d stimuli) | {len(c16t[c]['trials'])} | " + ' | '.join(row) + f' | {tot:.3f} |')
            J.setdefault('cells', {})[c + '_k16'] = {cls: cell_acc(c16t, c, cls) for cls in ['L', 'O', 'G', 'Ab', 'Cy']}
    md += ['', '### O − G per cell (identity/cancellation vs associativity; paired trial bootstrap)', '', '| cell | O − G [95% CI] |', '|---|---|']
    for c in sorted(cells, key=lambda s: (s[:2], s)):
        tr = cells[c]['trials']
        if 'leak' in c or not A1.pooled(tr, 'G')[1]:
            continue
        rng = seed('OG', c)
        est = A1.pooled(tr, 'O')[0] - A1.pooled(tr, 'G')[0]; bs = []
        for _ in range(NB):
            i = rng.integers(0, len(tr), len(tr)); bs.append(A1.pooled(tr, 'O', i)[0] - A1.pooled(tr, 'G', i)[0])
        md.append(f'| {c} | {est:+.3f} [{np.nanpercentile(bs, 2.5):+.3f}, {np.nanpercentile(bs, 97.5):+.3f}] |')
    # ---- primary: steps 1-3
    md += ['', '## Primary: decision-rule steps 1-3 (base t0)', '', '| order | measure | acc_L [95% CI] (n L) | threshold | G t0 [CI] | g(G t0) [CI] | class |', '|---|---|---|---|---|---|---|']
    for n, pre in [(6, 'n6'), (8, 'n8'), (5, 'n5')]:
        for field, lab in [(0, 'accuracy'), (2, 'p_gold')]:
            s = steps123(cells, n, pre, field)
            if s:
                J.setdefault('steps', {})[f'{pre}_{lab}'] = s
                md.append(f"| n={n} | {lab} | {s['acc_L']:.3f} [{s['acc_L_ci'][0]:.3f}, {s['acc_L_ci'][1]:.3f}] ({s['n_L']}) | {s['threshold_L']:.3f} | "
                          f"{s['G_t0']:.3f} [{s['G_t0_ci'][0]:.3f}, {s['G_t0_ci'][1]:.3f}] | {s['g_G_t0']:.2f} [{s['g_ci'][0]:.2f}, {s['g_ci'][1]:.2f}] | **{s['class']}** |")
    k16 = os.path.join(HERE, 'res', 'ica_best_k16.jsonl')
    if os.path.exists(k16):
        c16 = A1.load(k16)
        for field, lab in [(0, 'accuracy'), (2, 'p_gold')]:
            s = steps123(c16, 6, 'n6', field)
            if s:
                J.setdefault('steps', {})[f'n6_k16_{lab}'] = s
                md.append(f"| n=6, k=16 (2d stimuli) | {lab} | {s['acc_L']:.3f} [{s['acc_L_ci'][0]:.3f}, {s['acc_L_ci'][1]:.3f}] ({s['n_L']}) | {s['threshold_L']:.3f} | "
                          f"{s['G_t0']:.3f} [{s['G_t0_ci'][0]:.3f}, {s['G_t0_ci'][1]:.3f}] | {s['g_G_t0']:.2f} [{s['g_ci'][0]:.2f}, {s['g_ci'][1]:.2f}] | **{s['class']}** |")
    # ---- predictions
    P = {}
    s6 = J['steps']['n6_accuracy']
    P['P1 not R at n=6 (acc_L >= 0.417)'] = (s6['acc_L'] >= 0.417, f"acc_L {s6['acc_L']:.3f} [{s6['acc_L_ci'][0]:.3f}, {s6['acc_L_ci'][1]:.3f}]")
    P['P2 B-type at n=6'] = (s6['class'] == 'B-type', f"class {s6['class']}; g(G t0) {s6['g_G_t0']:.2f}")
    lk = cell_acc(cells, 'n6_leak_t1', 'G')[0]
    P['P3 leak t1 G >= 0.90'] = (lk >= 0.90, f'leak G {lk:.3f}')
    C = A1.load(os.path.join(ROOT, 'exp1', 'ideal', 'res', 'ideal_C.jsonl'))
    ta = cells['n6_base_t0']['trials']; tb = C['n6_base_t0']['trials']
    d4, ci4 = boot_diff(ta, tb, 'G', seed('P4'), paired=True)
    P['P4 G(n6 t0) > learner C (paired CI > 0)'] = (ci4[0] > 0, f'model − C = {d4:+.3f} [{ci4[0]:+.3f}, {ci4[1]:+.3f}]')
    d5, ci5 = boot_diff(cells['n6_base_t1']['trials'], cells['n6_base_t0']['trials'], 'G', seed('P5'))
    P['P5 n6 base t1 − t0 on G: CI includes 0'] = (ci5[0] <= 0 <= ci5[1], f't1 − t0 = {d5:+.3f} [{ci5[0]:+.3f}, {ci5[1]:+.3f}]')
    # P6: n8 unseen vs seen target types
    recs = [json.loads(l) for l in open(main_p, encoding='utf-8')]

    def by_seen(files):
        seen, unseen = [], []
        for r in recs:
            if r['file'][:-6] in files:
                per = defaultdict(lambda: [0, 0, 0.0])
                for q in r['queries']:
                    per[q['class']][0] += q['correct']; per[q['class']][1] += 1; per[q['class']][2] += q['p_gold']
                (seen if r['target_type'][1] in SEEN8 else unseen).append(dict(per))
        return seen, unseen
    se, un = by_seen({'n8_base_t0'})
    d6, ci6 = boot_diff(un, se, 'G', seed('P6'))
    P['P6 n8 base t0: unseen-type G < seen-type G (CI < 0)'] = (ci6[1] < 0, f'unseen − seen = {d6:+.3f} [{ci6[0]:+.3f}, {ci6[1]:+.3f}] (n trials {len(un)} / {len(se)})')
    se2, un2 = by_seen({'n8_base_t0', 'n8_base_t1', 'n8_heldout_t1'})
    d6b, ci6b = boot_diff(un2, se2, 'G', seed('P6b'))
    md += ['', '## Preregistered predictions', '', '| prediction | met? | evidence |', '|---|---|---|']
    for k, (ok, ev) in P.items():
        md.append(f"| {k} | {'**met**' if ok else '**not met**'} | {ev} |")
    md.append(f'| P6 secondary (pooled n8 cells) | {"met" if ci6b[1] < 0 else "not met"} | unseen − seen = {d6b:+.3f} [{ci6b[0]:+.3f}, {ci6b[1]:+.3f}] |')
    J['predictions'] = {k: {'met': bool(v[0]), 'evidence': v[1]} for k, v in P.items()}
    # by target type, n8
    md += ['', '### n=8 accuracy by target type and forcing class (seen in the model\'s training: Z8 = C8, D4)', '', '| cell | class | ' + ' | '.join(['Z8', 'D4', 'Z4xZ2', 'Z2^3', 'Q8']) + ' | seen | unseen |', '|---|---|---|---|---|---|---|---|---|']
    for cfile in ['n8_base_t0', 'n8_base_t1', 'n8_heldout_t1']:
        for cls in ['L', 'O', 'G']:
            acc = defaultdict(lambda: [0, 0])
            for r in recs:
                if r['file'][:-6] == cfile:
                    for q in r['queries']:
                        if q['class'] == cls:
                            acc[r['target_type'][1]][0] += q['correct']; acc[r['target_type'][1]][1] += 1
            grp = lambda ts: (sum(acc[t][0] for t in ts) / sum(acc[t][1] for t in ts)) if sum(acc[t][1] for t in ts) else float('nan')
            md.append(f'| {cfile} | {cls} | ' + ' | '.join(f'{acc[t][0] / acc[t][1]:.3f} (n={acc[t][1]})' if acc[t][1] else '—' for t in ['Z8', 'D4', 'Z4xZ2', 'Z2^3', 'Q8']) +
                      f' | {grp(["Z8", "D4"]):.3f} | {grp(["Z4xZ2", "Z2^3", "Q8"]):.3f} |')
    # ---- secondary: vs learner C and row/col elimination
    md += ['', '## Secondary: model vs learner C (count shortcut) and one-pass row/column elimination (expected accuracy)', '',
           '| cell | class | model | learner C | row/col elimination |', '|---|---|---|---|---|']
    for c in ['n6_base_t0', 'n6_base_t1', 'n8_base_t0', 'n5_base_t0']:
        h = heuristics(os.path.join(ROOT, 'exp1', 'stim', c + '.jsonl'))
        for cls in ['L', 'O', 'G']:
            a, n = cell_acc(cells, c, cls)
            if n:
                md.append(f'| {c} | {cls} | {a:.3f} | {h[cls][0]:.3f} | {h[cls][1]:.3f} |')
    # ---- cue sweep
    cal = os.path.join(HERE, 'res', 'ica_best_cal.jsonl')
    if os.path.exists(cal):
        md += ['', '## Secondary: cue sweep (n=6, t=0; L / O / G accuracy; raw and row-sorted)', '',
               '| file | k | L | O | G | all | learner C (all) | row/col (all) | Qwen3-8B-Base all (same t=0 trials) |', '|---|---|---|---|---|---|---|---|---|']
        cc = A1.load(cal)
        q8 = defaultdict(lambda: [0, 0])
        for l in open(os.path.join(ROOT, 'exp2', 'res', 'q8b_cal.jsonl'), encoding='utf-8'):
            r = json.loads(l)
            if r['t'] == 0:
                q8[r['file'][:-6]][0] += sum(q['correct'] for q in r['queries']); q8[r['file'][:-6]][1] += len(r['queries'])
        for c in sorted(cc, key=lambda s: (s.split('_')[0], int(s.split('_k')[1]))):
            h = heuristics(os.path.join(ROOT, 'exp2', 'stim', c + '.jsonl'), t0_only=True)
            vals = []
            for cls in ['L', 'O', 'G']:
                a, n = cell_acc(cc, c, cls)
                vals.append(f'{a:.3f} (n={n})' if n else '—')
            tot = sum(v[0] for t in cc[c]['trials'] for v in t.values()) / sum(v[1] for t in cc[c]['trials'] for v in t.values())
            md.append(f"| {c.split('_k')[0]} | {c.split('_k')[1]} | " + ' | '.join(vals) + f" | {tot:.3f} | {h['all'][0]:.3f} | {h['all'][1]:.3f} | "
                      f"{q8[c][0] / q8[c][1]:.3f} |")
            J.setdefault('sweep', {})[c] = {'all': tot, 'C': h['all'][0], 'rowcol': h['all'][1]}
    # ---- exploratory: interleaved, checkpoints
    il = os.path.join(HERE, 'res', 'ica_best_main_interleaved.jsonl')
    if os.path.exists(il):
        ci_ = A1.load(il)
        md += ['', '## Exploratory: interleaved fact order (all context facts in one random order)', '',
               '| cell | L | O | G | steps 1-3 class |', '|---|---|---|---|---|']
        for c in sorted(ci_):
            md.append(f'| {c} | ' + ' | '.join(f'{cell_acc(ci_, c, cls)[0]:.3f}' for cls in ['L', 'O', 'G']) + ' | ' +
                      (steps123(ci_, int(c[1]), c[:2])['class'] if c.endswith('base_t0') else '') + ' |')
    ck = sorted([f for f in os.listdir(os.path.join(HERE, 'res')) if f.startswith('ica_ckpt_')],
                key=lambda f: int(re.findall(r'\d+', f)[0]))
    if ck:
        md += ['', '## Exploratory: training trajectory (6 of the 21 released numbered checkpoints; n6 base t0, 2 draws; sweep t0)', '',
               '| step | acc_L | O t0 | G t0 | g(G t0) | class | sweep k=10 all | sweep k=28 all |', '|---|---|---|---|---|---|---|---|']
        for f in ck:
            cs = A1.load(os.path.join(HERE, 'res', f)); s = steps123(cs, 6, 'n6')
            sw = lambda c: (sum(v[0] for t in cs[c]['trials'] for v in t.values()) / sum(v[1] for t in cs[c]['trials'] for v in t.values())) if c in cs else float('nan')
            md.append(f"| {re.findall(r'\d+', f)[0]} | {s['acc_L']:.3f} | {cell_acc(cs, 'n6_base_t0', 'O')[0]:.3f} | {s['G_t0']:.3f} | {s['g_G_t0']:.2f} | {s['class']} | {sw('ks_n6_k10'):.3f} | {sw('ks_n6_k28'):.3f} |")
    txt = '\n'.join(md); print(txt)
    open(os.path.join(HERE, 'RESULTS_tables.md'), 'w', encoding='utf-8').write(txt + '\n')
    json.dump(J, open(os.path.join(HERE, 'results6.json'), 'w'), indent=1, default=float)


if __name__ == '__main__':
    main()

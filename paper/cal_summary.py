"""Calibration summary for the paper (post-audit, 2026-10-09): all 8 calibrated LMs + A4.
- L accuracy pooled over t by k, with k28 - k10 (independent-trial bootstrap);
- sorted - raw on L cells at k = 16/22/28 (paired: identical trials);
- instructed - raw at k = 10/22 per class, pooled over t (paired), with the preregistered n >= 30 guard (L-cell guard of 2a, applied to every class).
Per-test seeds. -> cal_summary.md, cal_summary.json"""
import json, os, zlib
from collections import defaultdict
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
MODELS = [('q06b', 'Qwen3-0.6B-Base', 'exp2/res/q06b_cal.jsonl'), ('q17', 'Qwen3-1.7B', 'exp2/res/q17_cal.jsonl'),
          ('smol17', 'SmolLM2-1.7B', 'exp2/res/smol17_cal.jsonl'), ('q17b', 'Qwen3-1.7B-Base', 'exp2/res/q17b_cal.jsonl'),
          ('q4b', 'Qwen3-4B-Base (nf4†)', 'exp2/res/q4b_cal.jsonl'), ('q8b', 'Qwen3-8B-Base (nf4†)', 'exp2/res/q8b_cal.jsonl'),
          ('olmo1b', 'OLMo-2-1B', 'exp2/res/olmo1b_cal.jsonl'), ('olmo7b', 'OLMo-2-7B (nf4†)', 'exp2/res/olmo7b_cal.jsonl'),
          ('A4', 'A4 (trained, 4 layers)', 'exp3/res_cal/A4_cal.jsonl')]
NB, GUARD = 2000, 30


def load(p):
    """{(variant, k): {(t, trial): {class: [correct, n]}}}"""
    D = defaultdict(dict)
    for l in open(os.path.join(ROOT, p), encoding='utf-8'):
        r = json.loads(l)
        var = 'instr' if r['file'].startswith('ki_') else ('sorted' if r['file'].startswith('kso_') else 'raw')
        per = defaultdict(lambda: [0, 0])
        for q in r['queries']:
            per[q['class']][0] += q['correct']; per[q['class']][1] += 1
        D[(var, r['k'])][(r['t'], r['trial'])] = dict(per)
    return D


def acc(trials, keys, c):
    n = sum(trials[k][c][1] for k in keys if c in trials[k])
    return (sum(trials[k][c][0] for k in keys if c in trials[k]) / n if n else np.nan), n


def seed(*xs):
    return np.random.default_rng([zlib.crc32(str(x).encode()) for x in xs])


def boot(a, b, c, paired, rng):
    ka, kb = sorted(a), sorted(b)
    out = []
    for _ in range(NB):
        ia = rng.integers(0, len(ka), len(ka)); ib = ia if paired else rng.integers(0, len(kb), len(kb))
        out.append(acc(a, [ka[i] for i in ia], c)[0] - acc(b, [kb[i] for i in ib], c)[0])
    return [float(x) for x in np.nanpercentile(out, [2.5, 97.5])]


def main():
    md = ['# Calibration summary (auto-generated by paper/cal_summary.py; n=6, chance 0.167)', '',
          '## L accuracy by k (pooled over t = 0, 4)', '', '| model | k=10 | k=16 | k=22 | k=28 | k28 − k10 [95% CI] |', '|---|---|---|---|---|---|']
    J = {}
    for name, lab, p in MODELS:
        if not os.path.exists(os.path.join(ROOT, p)):
            continue
        D = load(p); J[name] = res = {'label': lab}
        row = []
        for k in (10, 16, 22, 28):
            a, n = acc(D[('raw', k)], list(D[('raw', k)]), 'L'); row.append(f'{a:.3f}'); res[f'L_k{k}'] = (a, n)
        d = res['L_k28'][0] - res['L_k10'][0]; ci = boot(D[('raw', 28)], D[('raw', 10)], 'L', False, seed(name, 'k28-k10'))
        res['k28_minus_k10'] = (d, ci)
        md.append(f'| {lab} | ' + ' | '.join(row) + f' | {d:+.3f} [{ci[0]:+.3f}, {ci[1]:+.3f}] |')
    md += ['', '## Sorted minus raw, L cells (paired; same trials)', '', '| model | k=16 | k=22 | k=28 |', '|---|---|---|---|']
    for name, lab, p in MODELS:
        if name not in J or ('sorted', 28) not in load(os.path.join(ROOT, p)):
            continue
        D = load(p); cells = []
        for k in (16, 22, 28):
            s, r = D[('sorted', k)], D[('raw', k)]
            common = sorted(set(s) & set(r))
            d = acc(s, common, 'L')[0] - acc(r, common, 'L')[0]
            ci = boot({x: s[x] for x in common}, {x: r[x] for x in common}, 'L', True, seed(name, 'sorted', k))
            J[name][f'sorted_minus_raw_k{k}'] = (d, ci, acc(s, common, 'L')[0])
            cells.append(f'{d:+.3f} [{ci[0]:+.3f}, {ci[1]:+.3f}]')
        md.append(f'| {lab} | ' + ' | '.join(cells) + ' |')
    md += ['', f'## Instructed minus raw (paired; pooled over t; cells with ≥{GUARD} queries)', '', '| model | k | L | O | G |', '|---|---|---|---|---|']
    allc = []
    for name, lab, p in MODELS:
        if name not in J:
            continue
        D = load(p)
        if ('instr', 10) not in D:
            continue
        for k in (10, 22):
            s, r = D[('instr', k)], D[('raw', k)]; common = sorted(set(s) & set(r)); cells = []
            for c in 'LOG':
                a1, n = acc(s, common, c); a0, _ = acc(r, common, c)
                if n < GUARD:
                    cells.append(f'— (n={n})'); continue
                ci = boot({x: s[x] for x in common}, {x: r[x] for x in common}, c, True, seed(name, 'instr', k, c))
                allc.append((name, k, c, a1 - a0, ci, n)); cells.append(f'{a1 - a0:+.3f} [{ci[0]:+.3f}, {ci[1]:+.3f}] (n={n})')
            md.append(f'| {lab} | {k} | ' + ' | '.join(cells) + ' |')
    LG = [x for x in allc if x[2] in 'LG' and x[0] != 'A4']
    ds = [x[3] for x in LG]
    md += ['', f'L and G contrasts over the {len({x[0] for x in LG})} LMs: {len(ds)} contrasts, range {min(ds):+.3f} to {max(ds):+.3f}, mean {np.mean(ds):+.4f}; '
           f'CI excludes 0 in {sum(1 for x in LG if x[4][0] > 0 or x[4][1] < 0)}.']
    da = [x[3] for x in allc if x[0] != 'A4']
    md.append(f'All classes: {len(da)} contrasts, range {min(da):+.3f} to {max(da):+.3f}, mean {np.mean(da):+.4f}; CI excludes 0 in '
              f'{sum(1 for x in allc if x[0] != "A4" and (x[4][0] > 0 or x[4][1] < 0))}.')
    J['_instructed'] = {'LG': {'n': len(ds), 'min': min(ds), 'max': max(ds), 'mean': float(np.mean(ds))}, 'all': allc}
    txt = '\n'.join(md); print(txt)
    open(os.path.join(HERE, 'cal_summary.md'), 'w', encoding='utf-8').write(txt + '\n')
    json.dump(J, open(os.path.join(HERE, 'cal_summary.json'), 'w'), indent=1, default=float)


if __name__ == '__main__':
    main()
